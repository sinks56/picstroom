#!/usr/bin/env python3
"""Generates the home-screen widget layouts (android/app/src/main/res/layout/widget_*.xml).

Each layout = black frame + one ImageView (the collage bitmap drawn by the app) + an
invisible grid of tap targets (hit0..hit4) that matches the collage cells, + the shuffle
button. The cell structure is read from CollageLayout.java so both stay in step
(CollageLayoutResourcesTest checks it).

Run:  python3 scripts/gen-widget-layouts.py
"""
import re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
JAVA = ROOT / "android/app/src/main/java/io/github/sinks56/picstroom/widget/CollageLayout.java"
OUT = ROOT / "android/app/src/main/res/layout"

specs = re.findall(r'"(c\d(?:_[a-z]+)?)\|([^"]+)"', JAVA.read_text())

def parse(s, i=0):
    """-> (node, next_index); node = ('leaf', idx) | (dir, [(weight, node), ...])"""
    c = s[i]
    if c in "HV":
        i += 2
        kids = []
        while True:
            j = i
            while s[j].isdigit(): j += 1
            w = int(s[i:j]); i = j + 1
            node, i = parse(s, i)
            kids.append((w, node))
            if s[i] == ",": i += 1; continue
            break
        return (c, kids), i + 1
    j = i
    while j < len(s) and s[j].isdigit(): j += 1
    return ("leaf", int(s[i:j])), j

def transpose(n):
    if n[0] == "leaf": return n
    d = "V" if n[0] == "H" else "H"
    return (d, [(w, transpose(k)) for w, k in n[1]])

def emit(node, parent_dir, weight, indent):
    pad = "    " * indent
    if node[0] == "leaf":
        if parent_dir is None:
            wh = 'android:layout_width="match_parent"\n{p}    android:layout_height="match_parent"'.format(p=pad)
        elif parent_dir == "H":
            wh = 'android:layout_width="0dp"\n{p}    android:layout_height="match_parent"\n{p}    android:layout_weight="{w}"'.format(p=pad, w=weight)
        else:
            wh = 'android:layout_width="match_parent"\n{p}    android:layout_height="0dp"\n{p}    android:layout_weight="{w}"'.format(p=pad, w=weight)
        return f'{pad}<FrameLayout\n{pad}    android:id="@+id/hit{node[1]}"\n{pad}    {wh} />\n'
    d, kids = node
    orient = "horizontal" if d == "H" else "vertical"
    if parent_dir is None:
        wh = 'android:layout_width="match_parent"\n{p}    android:layout_height="match_parent"'.format(p=pad)
    elif parent_dir == "H":
        wh = 'android:layout_width="0dp"\n{p}    android:layout_height="match_parent"\n{p}    android:layout_weight="{w}"'.format(p=pad, w=weight)
    else:
        wh = 'android:layout_width="match_parent"\n{p}    android:layout_height="0dp"\n{p}    android:layout_weight="{w}"'.format(p=pad, w=weight)
    s = f'{pad}<LinearLayout\n{pad}    {wh}\n{pad}    android:orientation="{orient}">\n'
    for w, k in kids:
        s += emit(k, d, w, indent + 1)
    return s + f"{pad}</LinearLayout>\n"

TEMPLATE = '''<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by scripts/gen-widget-layouts.py - do not edit. -->
<FrameLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:layout_width="match_parent"
    android:layout_height="match_parent"
    android:background="#000000">

    <ImageView
        android:id="@+id/collage"
        android:layout_width="match_parent"
        android:layout_height="match_parent"
        android:contentDescription="@null"
        android:scaleType="centerCrop" />

    <!-- tap targets, one per picture -->
{hits}
    <ImageView
        android:id="@+id/shuffle"
        android:layout_width="30dp"
        android:layout_height="30dp"
        android:layout_gravity="top|end"
        android:background="#99000000"
        android:contentDescription="@string/widget_shuffle"
        android:padding="7dp"
        android:scaleType="fitCenter"
        android:src="@drawable/ic_shuffle"
        android:visibility="gone" />
</FrameLayout>
'''

OUT.mkdir(parents=True, exist_ok=True)
for name, spec in specs:
    node, _ = parse(spec)
    variants = [("w", node)] if name == "c1" else [("w", node), ("t", transpose(node))]
    for suffix, n in variants:
        fname = f"widget_{name}" if name == "c1" else f"widget_{name}_{suffix}"
        hits = emit(n, None, 1, 1)
        (OUT / f"{fname}.xml").write_text(TEMPLATE.format(hits=hits))
        print("wrote", fname)
